# app/src/tasks/debate_round1.py

from crewai import Task

DIFFICULTY_LEVELS = """
[난이도 단계별 구조]
1단계: 자음+모음 (예: 가/다/라/바 - 받침 없는 기본 단어)
2단계: 자음+모음+자음 (예: 각/난/달/밤 - 받침 있는 단순 단어)
3단계: 자음+이중모음+모음 (예: 뼈/궤/쥐 - 이중모음 포함)
4단계: 2음절 단어 (예: 나비/가방 - 단순 2음절)
5단계: 자음+이중모음+받침, 복합(예: 괭/쓩 등)
6단계: 복합 2음절 (예: 완벽한 난이도 최고 단어)
"""

EXPLORATIONS = """
[탐험 유형별 구성]
탐험1: 같은 음소 찾기 (자음자 또는 모음자)
탐험2: 단어 인식 (그림 → 정답 단어 매칭)
탐험3: 단어 구별 (무의미/의미 단어 중 맞는 단어 찾기)
탐험4: 단어 말하기 (음성 인식)
- 각 탐험 당 최소 1~3문제씩 배정 권장, 주간 총 합은 10~15문제 내외
"""

def build(agent, student_data=None):
    """
    학생 데이터 기반, 부족한 부분 진단 + 주차별 학습 상담(진단 및 예비 커리큘럼 설계)
    """
    description = (
        "당신은 난독증 전문가 치료사입니다. 아래 학생 데이터와 난이도 기준표를 참고해, "
        "실제 대화하듯 학생의 학습 상태를 진단하고, 부모,심리코치와 상호작용하며 다음 주 학습 방향을 논의해주세요.\n\n"
        f"{DIFFICULTY_LEVELS}\n"
        f"{EXPLORATIONS}\n"
        "- 요일별로 어떤 탐험(1~4)이 몇 문제씩 배치되고, 난이도와 목표가 어떻게 조정되는지 꼭 대화와 근거로 명확히 나와야 합니다.\n"
        "- 각 대화에서는 치료사가 단계·탐험별 배경과 실제 예시문제를 제시하고, 부모,심리코치 피드백과 학생 반응, 난이도/문제수/흥미도에 관한 실제 협의가 이뤄집니다.\n"
        "- 마지막엔 요일별 목표(요일별 탐험유형+문제수+난이도/목적)를 한글 자연어로 표처럼 요약하세요.\n"
        "- 각 단계의 예시도 반드시 참고해 대화와 제안, 단어 추천, 진단에 반영하세요.\n"
        "- 요일별로 탐험 1,2,3,4가 모두 포함되도록 계획하세요.\n"
        "- 요일별로 문제수는 10문제로 맞추세요.\n"
        "- 학생의 성공률이 50% 이하일 때는 이전 단계, 80% 이상이면 다음 단계로 난이도 조정안을 대화 중 반드시 언급하세요.\n"
        "\n\n"
        "== 대화 흐름 요구 ==\n"
        "1. 치료사가 학생의 약점/착오(자모 혼동, 오답 등)를 설명하며 출발합니다.\n"
        "2. 학부모·심리코치가 '난이도가 너무 어렵지는 않은가?', '어떤 단어로 진행할 건가?', '아이가 재미있게 할 수 있을까?' 등 질문·피드백을 자유롭게 추가합니다.\n"
        "3. 치료사는 난이도 조정 근거, 단어(예시), 커리큘럼 목표, 진행 방침을 단계별로 구체적이고 짧은 응답(1~2문장)으로 답해갑니다.\n"
        "4. 월~금 매일의 간단 목표(‘무슨 단계, 어떤 연습, 왜 이게 필요한가’)를 마지막에 요약하세요. 꼭 줄글(대화 순서)->목표 요약 형태!\n\n"
        "== 출력 예시 ==\n"
        "[대화]\n"
        "치료사: 아이는 ㄱ, ㄴ 자모를 많이 혼동하고, 성공률이 60% 수준이라 2단계(자음+모음+자음)에서 더 연습이 필요해요.\n"
        "부모: 계속 2단계만 하면 지루해하지 않나요?\n"
        "치료사: 월~수는 2단계 단어만, 목~금은 3단계(이중모음) 단어도 1~2개씩 추가해 흥미를 줄 예정입니다.\n"
        "심리코치: 과부담은 없을까요?\n"
        f"치료사: 하루 10문제 내외로 맞추고, {student_data['small_interest_name']}를 반영하여 흥미 자극도 함께 넣겠습니다.\n"
        "...\n"
        "...[요일별 목표 요약]\n"
        "월: 탐험1(자음) 2문제, 탐험2 2문제(2단계 단어), 탐험3 1문제(쉬운 문제 위주), 탐험4 1문제\n"
        "화: 탐험1 2문제, 탐험3 1문제(쉬운 문제 위주)\n"
        "수: 탐험2(그림-단어) 2문제, 탐험4(음성) 1문제\n"
        "목: 탐험1 2문제, 탐험3 1문제(3단계 혼합)\n"
        f"금: 탐험4(음성+{student_data['small_interest_name']}) 2문제, 탐험2 2문제\n"
        "✅ 리스트, 코드, 영어, 키값 못씀. 대화체+요일별 목표만 한국어 자연스러운 줄글. 단계별 근거, 단어 추천, 난이도 조정, 피드백 전부 대화처럼!\n"
        f"\n# 학생 데이터:\n{student_data}\n"
        "- 대화 마지막에는 반드시 '논의 및 합의 요약:'으로 시작하는 전체 협의 요약을 한국어로 자연스럽게 추가하세요. 3문단 이상 작성 필수!"
    )
    return Task(
        description=description,
        agent=agent,
        expected_output="""
            [대화]
            치료사: ...
            부모: ...
            심리코치: ...
            학생: ...
            ...

            [월~금 커리큘럼]  
            월요일: 탐험1(2문제, 자음 구별), 탐험2(3문제, 그림카드 매칭), 탐험3(3문제, 단어구별), 탐험4(2문제, 소리·놀이)
            화요일: ...
            수요일: ...
            목요일: ...
            금요일: ...
        """
     )
