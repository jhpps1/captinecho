#src/tasks/consensus.py

from crewai import Task

def build(agent, context_tasks):
    description = (
        "학생 협의 결과를 반드시 두 항목(커리큘럼 요약, 논의 및 합의 요약)으로만 한글 줄글로 요약하세요.\n\n"
        "커리큘럼 요약: 반드시 이번 주 탐험별 학습 내용과 문제 수(탐험1: 같은 음소 찾기, 탐험2: 그림을 통한 단어인식, 탐험3: 맞는 단어 찾기(무의미/의미 구별), 탐험4: 단어 말하기(음성)), 그리고 전체 목표(예시: 총 10문제/주)를 1~2 줄로 구체적이고 명확하게 요약하세요.\n"
        "논의 및 합의 요약: 반드시 이 부분에만 교육 전문가 논의/합의/부모소견/심리 피드백 등 요약문장으로 작성하세요.\n\n"
        "출력은 아래 예시처럼 두 항목 모두 포함, 구분자(항목명:)와 줄글 외 내용 절대 추가 금지!\n"
        "커리큘럼 요약: 이번 주 아이의 약점(예: 음소 분리) 및 개별 목표에 따라, 탐험1~4별로 며칠에 몇 문제씩 어떤 방식으로 학습이 진행될 것인지 구체적으로 써주세요. 예시는 다음과 같습니다:\n"
        "예) 이번주는 아이의 약점인 음소 분리 능력 강화를 위해, 매일 탐험1(같은 음소 찾기) 4문제, 탐험2(그림단어) 3문제, 탐험3(의미 구별) 3문제를 풀 예정입니다. 월요일은 탐험1 2문제, 탐험2 3문제, 탐험3 4문제, 탐험 4 1문제를, 화요일은 탐험 1 2문제, 탐험 2 3문제, 탐험 3 4문제, 탐험4 1문제를......풀 예정입니다.(월,화,수,목,금요일 전부 다 이런식으로 작성해줘) \n\n"
        "논의 및 합의 요약: academic, parent, wellbeing이 주장한것 또는 합의한 내용을 적어주세요. 예시는 다음과 같습니다:\n"
        "예) academic이 제안한 단계 조정: (...) parent가 제안한 단계조정: (...), wellbeing(학생) 이 제안한 단계조정: (...) 으로 모두가 합의하였습니다.\n\n"
        "리스트/코드/키워드/영어/키값 형태 모두 금지, 오직 자연스러운 한국어 문장만 허용됩니다."
        "구분자(커리큘럼 요약:, 논의 및 합의 요약:)는 꼭 출력해야함.\n"
    )
    return Task(
        description=description,
        agent=agent,
        context=context_tasks,
        expected_output="커리큘럼 요약:, 논의 및 합의 요약: 항목만 포함된 줄글"
    )
